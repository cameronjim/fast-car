"""The slice of vehicle_params the start-scan gate needs: LiDAR mount, body footprint, wheelbase and
the yaw-rate gain table.

Nothing here is a constant: every number comes from config/vehicle_params.yaml through the
generated binding (tools/gen_params.py). The node gets the binding from
`racer_tools.vehicle_params_loader`; offline code (replay, tests) gets the same generated object
from `load_live_vehicle`, which imports tools/gen_params.py by path exactly the way that loader
does (the same approach as racer_track_perception.vehicle).
"""

from __future__ import annotations

import importlib.util
import os
import sys
import types
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from racer_laps.scan_match import Body, Mount

_REPO_MARKER = Path("config") / "vehicle_params.yaml"


class VehicleParamsNull(ValueError):
    """A vehicle_params field this package needs is null (not yet measured)."""


@dataclass(frozen=True)
class LapVehicle:
    mount: Mount
    body: Body
    wheelbase_m: float
    yaw_gain_table: tuple[tuple[float, float], ...]


def from_generated(vp: Any) -> LapVehicle:
    """A LapVehicle from the generated VEHICLE_PARAMS object. Raises VehicleParamsNull if a field
    is null: the caller must refuse to start."""
    lidar = vp.sensors.lidar
    fields = {
        "sensors.lidar.mount_x_m": lidar.mount_x_m,
        "sensors.lidar.mount_y_m": lidar.mount_y_m,
        "sensors.lidar.mount_yaw_rad": lidar.mount_yaw_rad,
        "chassis.rear_overhang_m": vp.chassis.rear_overhang_m,
        "chassis.front_overhang_m": vp.chassis.front_overhang_m,
        "chassis.wheelbase_m": vp.chassis.wheelbase_m,
        "chassis.width_m": vp.chassis.width_m,
    }
    for name, value in fields.items():
        if value is None:
            raise VehicleParamsNull(f"vehicle_params {name} is null; refusing to continue")
    table = tuple((float(p.abs_angle_rad), float(p.gain)) for p in vp.steering.yaw_rate_gain_table)
    wheelbase = float(vp.chassis.wheelbase_m)
    return LapVehicle(
        mount=Mount(float(lidar.mount_x_m), float(lidar.mount_y_m), float(lidar.mount_yaw_rad)),
        body=Body(
            x_min_m=-float(vp.chassis.rear_overhang_m),
            x_max_m=wheelbase + float(vp.chassis.front_overhang_m),
            half_width_m=float(vp.chassis.width_m) / 2.0,
        ),
        wheelbase_m=wheelbase,
        yaw_gain_table=table,
    )


def find_repo_root(start: Path | None = None) -> Path:
    env = os.environ.get("RACER_REPO_ROOT")
    if env and (Path(env) / _REPO_MARKER).is_file():
        return Path(env)
    starts = [start] if start is not None else [Path(__file__).resolve(), Path.cwd()]
    for s in starts:
        for parent in [s, *s.parents]:
            if (parent / _REPO_MARKER).is_file():
                return parent
    raise FileNotFoundError(
        "cannot find the repo root (config/vehicle_params.yaml); set RACER_REPO_ROOT"
    )


def load_generated_params(repo_root: Path | None = None) -> Any:
    """Regenerate the Python vehicle_params binding from the committed yaml and return its
    VEHICLE_PARAMS instance. Refuses (raises) if the yaml fails its schema. Needs pyyaml and
    jsonschema (the `replay` extra)."""
    root = repo_root if repo_root is not None else find_repo_root()
    gen_path = root / "tools" / "gen_params.py"
    spec = importlib.util.spec_from_file_location("racer_laps._gen_params", gen_path)
    if spec is None or spec.loader is None:  # pragma: no cover - defensive
        raise ImportError(f"cannot load {gen_path}")
    gen = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = gen
    spec.loader.exec_module(gen)
    params = gen.load_yaml_file(root / "config" / "vehicle_params.yaml")
    schema = gen.load_schema_file(root / "config" / "vehicle_params.schema.json")
    gen.validate_params(params, schema)
    source = gen.generate_python(params, schema)
    module = types.ModuleType("racer_laps._vehicle_params_generated")
    module.__file__ = "<generated by tools/gen_params.py, not committed>"
    sys.modules[module.__name__] = module
    exec(compile(source, module.__file__, "exec"), module.__dict__)  # noqa: S102
    return module.VEHICLE_PARAMS


def load_live_vehicle(repo_root: Path | None = None) -> LapVehicle:
    """The live vehicle_params as a LapVehicle, for offline code."""
    return from_generated(load_generated_params(repo_root))
