"""Cut the second committed real-scan fixture (P1.6) and write its golden `geometric-v1` output.

    cd training/racer_pnp_perception
    uv run --group bags python ../../ros_ws/src/racer_track_perception/tests/make_real_scans_2026_11_13.py

45 scans from the TRAIN segments of the 2026-11-13 bags (G1a, G2, R0, R1 of the pre-registered
split; never a held-out segment), picked from the self-labelled scans of
/Users/cameronjim/code/car-data/pnp/selflabels-v0.2/. The loop is 7.4 m round, so every scan sees a
bend; the label (geometry seen later by the same sensor) gives the pick rule: per direction of
travel (ccw: the track turns left, cw: right) the labelled scans are ranked by the sideways offset
of station 5 (1.0 m ahead), and 7 scans are taken at evenly spaced ranks inside each of three
bands of that rank: the 0 to 20 percent band (straightest, "straight"), the 40 to 60 percent band
("corner entry") and the 80 to 100 percent band ("mid corner"). That is 42 scans. Three more scans
(one per band, both directions mixed) have a 40 degree sector blanked (NaN) as a fault injection
on a real scan: "dropped sector". Ranges are stored as uint16 quarter millimetres (the LiDAR's own
resolution, so lossless; a beam that is not a return is 0 and reads back as inf) in a compressed
npz. The golden file holds what `core.TrackPerceiver(geometric)` gives on the stored scans.

Tolerance for the golden comparison: 0.02 m on x, y and both half widths (test_real_scans.py), the
same as the 2026-11-11 fixture. The existing 2026-11-11 golden is NOT regenerated by this script.
"""

from __future__ import annotations

import sys
from pathlib import Path

import numpy as np

FIXTURES = Path(__file__).parent / "fixtures"
SCANS = FIXTURES / "real_scans_2026-11-13.npz"
GOLDEN = FIXTURES / "real_scans_2026-11-13_golden.npz"
LABELS = Path("/Users/cameronjim/code/car-data/pnp/selflabels-v0.2")
BAGS = {
    "2026-11-13T22-00-40_car_teleop": ("G1a", "G2"),
    "2026-11-13T22-20-18_car_teleop": ("R0", "R1"),
}
QUANTUM_M = 0.00025
PER_BAND = 7
BANDS = {"straight": (0.0, 0.2), "corner entry": (0.4, 0.6), "mid corner": (0.8, 1.0)}
SECTOR_RAD = np.deg2rad(40.0)
SECTOR_CENTRES_DEG = (30.0, -90.0, 0.0)  # front left, right side, straight ahead


def quantise(ranges: np.ndarray) -> np.ndarray:
    r = np.asarray(ranges, dtype=np.float64)
    ok = np.isfinite(r) & (r > 0.0)
    q = np.zeros(r.shape, dtype=np.float64)
    q[ok] = np.round(r[ok] / QUANTUM_M)
    if q.max() > np.iinfo(np.uint16).max:
        raise ValueError("a range does not fit uint16 quarter millimetres")
    return q.astype(np.uint16)


def dequantise(q: np.ndarray) -> np.ndarray:
    out = q.astype(np.float32) / np.float32(1.0 / QUANTUM_M)
    out[q == 0] = np.inf
    return out


def pick() -> dict[str, np.ndarray]:
    from racer_track_perception.vehicle import load_live_vehicle

    mount_yaw = load_live_vehicle().mount.yaw_rad
    # (bag, segment, scan index, label y at station 5, direction) of every train label.
    pool: list[tuple[str, str, int, float, str]] = []
    for bag, (ccw_seg, cw_seg) in BAGS.items():
        with np.load(LABELS / f"{bag}.npz") as z:
            for seg, direction in ((ccw_seg, "ccw"), (cw_seg, "cw")):
                for k in np.flatnonzero((z["role"] == "train") & (z["segment"] == seg)):
                    pool.append(
                        (bag, seg, int(z["index"][k]), float(z["label"][k, 5, 1]), direction)
                    )
    picked: list[tuple[str, str, int, str, str, bool, float]] = []
    for direction in ("ccw", "cw"):
        sub = [r for r in pool if r[4] == direction]
        order = np.argsort([abs(r[3]) for r in sub], kind="stable")
        for band, (lo, hi) in BANDS.items():
            lo_i = int(lo * len(sub))
            hi_i = max(int(hi * len(sub)), lo_i + PER_BAND)
            for rank in np.linspace(lo_i, hi_i - 1, PER_BAND).round().astype(int):
                bag, seg, i, _y5, _d = sub[int(order[rank])]
                picked.append((bag, seg, i, direction, band, False, 0.0))
    # Three fault injected scans: a middle scan of each band, with a sector blanked.
    for band, centre in zip(BANDS, SECTOR_CENTRES_DEG, strict=True):
        same = [m for m in picked if m[4] == band]
        bag, seg, i, direction, _b, _d, _c = same[len(same) // 2]
        picked.append((bag, seg, i, direction, band, True, centre))
    ranges = np.zeros((len(picked), 720), dtype=np.uint16)
    stamp = np.zeros(len(picked))
    geometry = (0.0, 0.0, 0.0, 0.0)
    cache: dict[str, dict[str, np.ndarray]] = {}
    for k, (bag, _seg, i, _dir, _band, dropped, centre) in enumerate(picked):
        if bag not in cache:
            with np.load(LABELS / "cache" / f"{bag}.scans.npz") as c:
                cache[bag] = {
                    n: c[n]
                    for n in (
                        "ranges",
                        "log_s",
                        "angle_min",
                        "angle_increment",
                        "range_min",
                        "range_max",
                    )
                }
        c = cache[bag]
        r = np.array(c["ranges"][i], dtype=np.float32)
        geometry = (
            float(c["angle_min"]),
            float(c["angle_increment"]),
            float(c["range_min"]),
            float(c["range_max"]),
        )
        stamp[k] = float(c["log_s"][i])
        if dropped:
            bearing = geometry[0] + np.arange(720) * geometry[1] + mount_yaw
            delta = np.abs(np.mod(bearing - np.deg2rad(centre) + np.pi, 2 * np.pi) - np.pi)
            r[delta <= SECTOR_RAD / 2.0] = np.nan
        ranges[k] = quantise(r)
    return {
        "ranges_q": ranges,
        "stamp_s": stamp,
        "angle_min": np.float64(geometry[0]),
        "angle_increment": np.float64(geometry[1]),
        "range_min": np.float64(geometry[2]),
        "range_max": np.float64(geometry[3]),
        "bag": np.array([m[0] for m in picked]),
        "segment": np.array([m[1] for m in picked]),
        "direction": np.array([m[3] for m in picked]),
        "kind": np.array([m[4] for m in picked]),
        "dropped_sector": np.array([m[5] for m in picked]),
    }


def run_geometric(path: Path = SCANS) -> dict[str, np.ndarray]:
    from racer_track_perception import core
    from racer_track_perception.vehicle import load_live_vehicle

    perceiver = core.TrackPerceiver(core.BACKEND_GEOMETRIC, load_live_vehicle())
    with np.load(path) as d:
        ranges = dequantise(d["ranges_q"])
        meta = (
            float(d["angle_min"]),
            float(d["angle_increment"]),
            float(d["range_min"]),
            float(d["range_max"]),
        )
    cols: dict[str, list] = {k: [] for k in ("x", "y", "hl", "hr", "sigma", "valid")}
    for r in ranges:
        t = perceiver.process(r, *meta)
        cols["x"].append(t.x_m)
        cols["y"].append(t.y_m)
        cols["hl"].append(t.half_width_left_m)
        cols["hr"].append(t.half_width_right_m)
        cols["sigma"].append(t.sigma_m)
        cols["valid"].append(t.valid_count)
    return {k: np.array(v) for k, v in cols.items()}


def main() -> int:
    fixture = pick()
    FIXTURES.mkdir(parents=True, exist_ok=True)
    np.savez_compressed(SCANS, **fixture)
    golden = run_geometric(SCANS)
    np.savez_compressed(GOLDEN, **golden)
    print(
        f"wrote {SCANS} ({SCANS.stat().st_size} bytes) and {GOLDEN} ({GOLDEN.stat().st_size} bytes): "
        f"{len(golden['valid'])} scans, mean valid {golden['valid'].mean():.2f}"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
