"""L1 of the deskew relay's decisions (ROS-free): the wheel-model yaw rate, which odometry a sweep
is paired with under each `stamp_is`, every pass-through reason, ignored stuck samples, the status
JSON, and the end-to-end round trip (a stream of sweeps with a twist that changes every sweep,
generated by the independent ray caster, through `DeskewRelay.process`)."""

from __future__ import annotations

import json
import math

import numpy as np
import pytest
from deskew_sim import ROOM, reference_truth_distance, sweep
from racer_track_perception import deskew, deskew_relay
from racer_track_perception.deskew import DeskewConfig
from racer_track_perception.deskew_relay import DeskewRelay, DeskewStats
from racer_track_perception.vehicle import load_generated_params

N = 720
INC = 2.0 * math.pi / 719.0
DT = 1.0e-4 * 10 / 7.2
SWEEP_S = DT * (N - 1)
SCAN_PERIOD_S = 0.1
WALL_TOLERANCE_M = 0.02
# Pairing a sweep with the odometry of the wrong half second (stamp_is wrong) must leave a larger
# wall error than the right pairing by at least this factor.
WRONG_PAIRING_FACTOR = 3.0


@pytest.fixture(scope="module")
def table() -> tuple[tuple[float, float], ...]:
    vp = load_generated_params()
    return tuple((float(p.abs_angle_rad), float(p.gain)) for p in vp.steering.yaw_rate_gain_table)


def relay(live, table, stamp_is="sweep_start", order="index_ascending", **kw) -> DeskewRelay:
    cfg = DeskewConfig(stamp_is=stamp_is, beam_order=order, **kw)
    return DeskewRelay(cfg, live.mount, live.body, table)


def feed(
    r: DeskewRelay, t0: float, t1: float, v: float, delta: float, rate_hz: float = 50.0
) -> None:
    """Odometry and drive samples with stamps t0 <= t < t1; arrival = stamp + 1 ms."""
    t = t0
    while t < t1 - 1e-12:
        r.on_odom(t + 0.001, t, v)
        r.on_drive(t + 0.001, t, delta)
        t += 1.0 / rate_hz


def process(r: DeskewRelay, now: float, stamp: float, ranges=None, scan_time=SWEEP_S, dt=DT):
    ranges = np.full(N, 2.0) if ranges is None else ranges
    return r.process(now, stamp, ranges, -math.pi, INC, 0.05, 16.0, scan_time, dt)


# -- the yaw rate ------------------------------------------------------------------------------------


def test_yaw_rate_is_gain_times_v_tan_delta_over_the_wheelbase(table) -> None:
    L = 0.3302
    got = deskew_relay.wheel_yaw_rate(1.0, 0.2, L, table)
    assert got == pytest.approx(0.96 * math.tan(0.2) / L, rel=1e-6)  # the 0.20 rad knot is 0.96
    # between knots: linear
    got = deskew_relay.wheel_yaw_rate(1.0, 0.15, L, table)
    gain = 0.5 * (1.12 + 0.96) if abs(table[0][0] - 0.10) < 1e-9 else None
    if gain is not None:
        assert got == pytest.approx(gain * math.tan(0.15) / L, rel=1e-6)


def test_yaw_rate_sign_follows_the_steering_and_the_speed(table) -> None:
    L = 0.3302
    left = deskew_relay.wheel_yaw_rate(1.0, 0.3, L, table)
    right = deskew_relay.wheel_yaw_rate(1.0, -0.3, L, table)
    assert left > 0 > right and left == pytest.approx(-right)  # the gain uses |delta|
    assert deskew_relay.wheel_yaw_rate(-1.0, 0.3, L, table) == pytest.approx(-left)
    assert deskew_relay.wheel_yaw_rate(1.0, 0.0, L, table) == 0.0


def test_yaw_gain_is_held_outside_the_knots_and_one_without_a_table() -> None:
    table = ((0.1, 1.1), (0.4, 0.9))
    assert deskew_relay.yaw_gain(table, 0.0) == 1.1
    assert deskew_relay.yaw_gain(table, 0.9) == 0.9
    assert deskew_relay.yaw_gain((), 0.3) == 1.0


# -- which odometry a sweep gets ------------------------------------------------------------------------


def test_stamp_is_decides_which_odometry_a_sweep_is_paired_with(live, table) -> None:
    start, end = relay(live, table, "sweep_start"), relay(live, table, "sweep_end")
    for r in (start, end):
        feed(r, 9.0, 10.0, 0.4, 0.0)  # slow before 10.0
        feed(r, 10.0, 10.09, 1.4, 0.0)  # fast from 10.0
    stamp = (
        10.0 + 0.5 * SWEEP_S - 0.0001
    )  # the middle is a hair before 10.0 if the stamp is the end
    now = stamp + SWEEP_S
    # header.stamp is the first beam: the sweep's middle is after 10.0 and it is fast
    twist, reason, _ = start.twist_for(now, stamp + 0.5 * SWEEP_S)
    assert reason == "" and twist.v_mps == pytest.approx(1.4)
    # header.stamp is the last beam: the same number puts the middle before 10.0, where it is slow
    mid_end = stamp - 0.5 * SWEEP_S
    twist, reason, _ = end.twist_for(now, mid_end)
    assert reason == "" and twist.v_mps == pytest.approx(0.4)


def test_process_pairs_by_the_hypothesis_through_the_header_stamp(live, table) -> None:
    for stamp_is, expected_v in (("sweep_start", 1.4), ("sweep_end", 0.4)):
        r = relay(live, table, stamp_is)
        feed(r, 9.0, 10.0, 0.4, 0.0)
        feed(r, 10.0, 10.09, 1.4, 0.0)
        stamp = (
            10.0 + 0.5 * SWEEP_S - 0.0001
        )  # the middle is a hair before 10.0 if the stamp is the end
        res = process(r, stamp + SWEEP_S, stamp)
        assert res.reason == "" and res.twist.v_mps == pytest.approx(expected_v)


# -- pass-through, one reason each ---------------------------------------------------------------------


def test_no_odometry_passes_the_scan_through(live, table) -> None:
    r = relay(live, table)
    res = process(r, 10.0, 9.9)
    assert res.ranges is None and res.reason == "no_odom" and res.stamp_offset_s == 0.0


def test_stale_odometry_passes_through(live, table) -> None:
    r = relay(live, table)
    feed(r, 9.0, 10.0, 1.0, 0.1)
    res = process(r, 10.0 + 0.5, 10.4)  # newest sample is 0.5 s old
    assert res.reason == "twist_stale" and res.ranges is None
    assert res.twist_age_s == pytest.approx(0.5, abs=0.03)


def test_a_sample_too_old_for_the_sweeps_middle_is_stale(live, table) -> None:
    r = relay(live, table, max_twist_age_s=0.05)
    feed(r, 9.0, 9.5, 1.0, 0.1)
    feed(r, 9.9, 10.0, 1.0, 0.1)  # a gap in the stream: the newest sample is fresh
    res = process(r, 10.0, 9.7)  # but the sample the sweep's middle (9.75) needs is 0.25 s old
    assert res.reason == "twist_stale"


def test_a_clock_that_went_backwards_passes_through(live, table) -> None:
    r = relay(live, table)
    feed(r, 9.0, 10.0, 1.0, 0.1)
    res = process(r, 3.0, 2.9)
    assert res.reason == "clock_jump" and res.ranges is None


def test_no_steering_passes_through(live, table) -> None:
    r = relay(live, table)
    t = 9.0
    while t < 10.0:
        r.on_odom(t + 0.001, t, 1.0)
        t += 0.02
    res = process(r, 10.1, 9.99)
    assert res.reason == "no_steering"


def test_standstill_passes_through_unchanged(live, table) -> None:
    r = relay(live, table)
    feed(r, 9.0, 10.0, 0.01, 0.3)
    res = process(r, 10.0, 9.9)
    assert res.reason == "standstill" and res.ranges is None and res.stamp_offset_s == 0.0


@pytest.mark.parametrize(
    ("scan_time", "dt"), [(0.0, 0.0), (math.nan, math.nan)], ids=["zero", "nan"]
)
def test_a_scan_with_no_timing_passes_through(live, table, scan_time, dt) -> None:
    r = relay(live, table)
    feed(r, 9.0, 10.0, 1.0, 0.1)
    assert process(r, 10.0, 9.9, scan_time=scan_time, dt=dt).reason == "no_timing"


@pytest.mark.parametrize("stamp", [0.0, -1.0, math.nan])
def test_a_scan_with_no_usable_stamp_passes_through(live, table, stamp) -> None:
    r = relay(live, table)
    feed(r, 9.0, 10.0, 1.0, 0.1)
    assert process(r, 10.0, stamp).reason == "bad_stamp"


def test_an_exception_in_the_core_passes_the_scan_through(live, table, monkeypatch) -> None:
    r = relay(live, table)
    feed(r, 9.0, 10.0, 1.0, 0.1)

    def boom(*a, **k):
        raise RuntimeError("core failure")

    monkeypatch.setattr(deskew, "deskew_scan", boom)
    res = process(r, 10.0, 9.9)
    assert res.reason == "exception" and res.ranges is None


def test_a_deskewed_scan_has_no_reason_and_a_stamp_offset(live, table) -> None:
    r = relay(live, table, "sweep_start")
    feed(r, 9.0, 10.0, 1.0, 0.2)
    res = process(r, 10.0, 9.9)
    assert res.reason == "" and res.ranges is not None and res.ranges.dtype == np.float32
    assert res.stamp_offset_s == pytest.approx(SWEEP_S, rel=1e-6)  # start stamp, end reference
    assert res.twist.yaw_rate_radps > 0.0


# -- stuck and jumping streams -----------------------------------------------------------------------------


def test_samples_whose_stamp_does_not_advance_are_ignored_and_the_stream_goes_stale(
    live, table
) -> None:
    r = relay(live, table)
    feed(r, 9.0, 10.0, 1.0, 0.1)
    last = r.odom.stamps[-1]
    for k in range(60):  # a stuck driver resends its last message with the same stamp
        r.on_odom(10.0 + k * 0.02, last, 1.0)
        r.on_drive(10.0 + k * 0.02, last, 0.1)
    assert r.odom.rejected == 60 and r.drive.rejected == 60
    res = process(r, 11.2, 11.1)
    assert res.reason == "twist_stale"


def test_a_stamp_that_jumps_back_is_ignored(live, table) -> None:
    r = relay(live, table)
    feed(r, 9.0, 10.0, 1.0, 0.1)
    feed(r, 5.0, 6.0, 1.0, 0.1)  # the stamps jump back 5 s: every sample is ignored
    assert r.odom.rejected == 50
    assert process(r, 10.0 + 0.5, 10.4).reason == "twist_stale"


def test_non_finite_samples_are_ignored(live, table) -> None:
    r = relay(live, table)
    r.on_odom(1.0, 1.0, math.nan)
    r.on_odom(math.nan, 1.0, 1.0)
    r.on_drive(1.0, 1.0, math.inf)
    assert r.odom.rejected == 2 and r.drive.rejected == 1 and not r.odom.stamps


def test_a_zero_stamp_falls_back_to_the_arrival_time(live, table) -> None:
    r = relay(live, table)
    r.on_odom(5.0, 0.0, 1.0)
    assert list(r.odom.stamps) == [5.0]


# -- the end-to-end round trip -----------------------------------------------------------------------------------


def _stream_error(live, table, true_stamp_is: str, claim_stamp_is: str) -> float:
    """Worst wall error over sweeps whose twist changes every sweep, deskewed by a relay that
    believes `claim_stamp_is` while the sweeps were stamped as `true_stamp_is`."""
    r = relay(live, table, claim_stamp_is)
    twists = [(0.6, 0.15), (1.4, -0.2), (0.8, 0.25), (1.5, -0.12)]
    worst = 0.0
    feed(r, 9.5, 10.0 - 0.01, *twists[3])  # the history a running stream already has
    for k in range(8):
        v, delta = twists[k % 4]
        t0 = 10.0 + k * SCAN_PERIOD_S  # first beam of sweep k
        feed(r, t0 - 0.01, t0 + SWEEP_S, v, delta)
        w = deskew_relay.wheel_yaw_rate(v, delta, live.body.wheelbase_m, table)
        ranges = sweep(live.mount, v, w, t_start=t0)
        stamp = t0 if true_stamp_is == "sweep_start" else t0 + SWEEP_S
        res = r.process(t0 + SWEEP_S + 0.002, stamp, ranges, -math.pi, INC, 0.05, 16.0, SWEEP_S, DT)
        assert res.ranges is not None, res.reason
        # the room frame of sweep(): the car starts at the origin at t0 with this sweep's twist
        dist = reference_truth_distance(
            res.ranges,
            live.mount,
            v,
            w,
            stamp + res.stamp_offset_s,
            -math.pi,
            INC,
            ROOM,
            t_start=t0,
        )
        worst = max(worst, float(dist.max()))
    return worst


@pytest.mark.parametrize("stamp_is", ["sweep_start", "sweep_end"])
def test_the_right_hypothesis_deskews_a_stream_to_within_2_cm(live, table, stamp_is) -> None:
    assert _stream_error(live, table, stamp_is, stamp_is) <= WALL_TOLERANCE_M


@pytest.mark.parametrize("stamp_is", ["sweep_start", "sweep_end"])
def test_the_wrong_hypothesis_pairs_the_wrong_odometry_and_is_worse(live, table, stamp_is) -> None:
    wrong = "sweep_end" if stamp_is == "sweep_start" else "sweep_start"
    right_err = _stream_error(live, table, stamp_is, stamp_is)
    wrong_err = _stream_error(live, table, stamp_is, wrong)
    assert wrong_err >= WRONG_PAIRING_FACTOR * right_err and wrong_err > 0.03, (
        right_err,
        wrong_err,
    )


def test_the_car_body_stays_where_it_is(live, table) -> None:
    r = relay(live, table)
    feed(r, 9.0, 10.0, 1.4, 0.3)
    ranges = np.full(N, 3.0)
    ranges[343:353] = 0.17  # the car's own parts
    res = process(r, 10.0, 9.9, ranges=ranges)
    assert res.ranges is not None
    assert np.allclose(res.ranges[343:353], 0.17, atol=1e-5)


# -- the status ----------------------------------------------------------------------------------------------------


def test_status_counts_every_scan_in_and_out_and_the_reasons(live, table) -> None:
    r = relay(live, table)
    stats = DeskewStats()
    results = [process(r, 10.0, 9.9)]  # no odometry
    feed(r, 9.0, 10.0, 1.0, 0.1)
    results += [process(r, 10.0, 9.9) for _ in range(3)]  # deskewed
    for res in results:
        stats.scan_in(10.0)
        stats.scan_out(res)
    d = stats.as_dict(10.2, odom_rejected=2, drive_rejected=1)
    assert d["scans_in"] == d["scans_out"] == 4
    assert d["scans_deskewed"] == 3 and d["scans_passed_through"] == 1
    assert d["passed_through_by_reason"]["no_odom"] == 1
    assert d["odom_samples_ignored"] == 2 and d["drive_samples_ignored"] == 1
    assert d["process_ms"]["p50"] is not None and d["process_ms"]["p99"] >= d["process_ms"]["p50"]
    assert d["process_ms"]["max"] >= d["process_ms"]["p99"]
    assert d["twist_age_s"] is not None and d["state"] == "running"
    json.loads(stats.as_json(10.2))  # strict JSON, no NaN


def test_status_before_any_scan_and_after_silence() -> None:
    stats = DeskewStats()
    d = stats.as_dict(1.0)
    assert d["state"] == "no_scan" and d["process_ms"] == {"p50": None, "p99": None, "max": None}
    stats.scan_in(1.0)
    assert stats.as_dict(1.5)["state"] == "running"
    assert stats.as_dict(3.0)["state"] == "no_scan"
