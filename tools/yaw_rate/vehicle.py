"""The vehicle_params fields this measurement reads, from the GENERATED Python binding.

Nothing physical is typed here (CLAUDE.md invariant 2). The binding is generated from
config/vehicle_params.yaml by tools/gen_params.py on every load, as
training/racer_pnp_dynamics/vehicle.py does, and validated against the schema.
"""

from __future__ import annotations

import sys
import types
from dataclasses import dataclass
from pathlib import Path
from typing import Any

REPO_ROOT = Path(__file__).resolve().parents[2]
PARAMS_PATH = REPO_ROOT / "config" / "vehicle_params.yaml"
SCHEMA_PATH = REPO_ROOT / "config" / "vehicle_params.schema.json"


@dataclass(frozen=True)
class Vehicle:
    wheelbase_m: float
    body_front_x_m: float  # wheelbase + front overhang
    body_rear_x_m: float  # rear overhang
    body_half_width_m: float
    lidar_x_m: float
    lidar_y_m: float
    lidar_yaw_rad: float
    schema_version: str


def load_binding(repo_root: Path = REPO_ROOT) -> Any:
    import gen_params

    params = gen_params.load_yaml_file(repo_root / "config" / "vehicle_params.yaml")
    schema = gen_params.load_schema_file(repo_root / "config" / "vehicle_params.schema.json")
    gen_params.validate_params(params, schema)
    source = gen_params.generate_python(params, schema)
    module = types.ModuleType("yaw_rate._vehicle_params_generated")
    module.__file__ = "<generated by tools/gen_params.py, not committed>"
    sys.modules[module.__name__] = module
    exec(compile(source, module.__file__, "exec"), module.__dict__)  # noqa: S102
    return module.VEHICLE_PARAMS


def load_vehicle(repo_root: Path = REPO_ROOT) -> Vehicle:
    vp = load_binding(repo_root)
    return Vehicle(
        wheelbase_m=float(vp.chassis.wheelbase_m),
        body_front_x_m=float(vp.chassis.wheelbase_m) + float(vp.chassis.front_overhang_m),
        body_rear_x_m=float(vp.chassis.rear_overhang_m),
        body_half_width_m=float(vp.chassis.width_m) / 2.0,
        lidar_x_m=float(vp.sensors.lidar.mount_x_m),
        lidar_y_m=float(vp.sensors.lidar.mount_y_m),
        lidar_yaw_rad=float(vp.sensors.lidar.mount_yaw_rad),
        schema_version=str(vp.meta.schema_version),
    )
