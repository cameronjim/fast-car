"""The vehicle_params fields the dynamics model needs, from the GENERATED Python binding.

Nothing physical is typed in this package (CLAUDE.md invariant 2). The binding is regenerated
from config/vehicle_params.yaml on every load with tools/gen_params.py, the same way
ros_ws/src/racer_tools/racer_tools/vehicle_params_loader.py does it. A field the model needs
that is null in the YAML is a refusal, not a default.
"""

from __future__ import annotations

import importlib.util
import sys
import types
from dataclasses import dataclass
from pathlib import Path
from typing import Any

PARAMS_RELATIVE = Path("config") / "vehicle_params.yaml"
SCHEMA_RELATIVE = Path("config") / "vehicle_params.schema.json"
GEN_PARAMS_RELATIVE = Path("tools") / "gen_params.py"


class VehicleParamsError(ValueError):
    """A vehicle_params field needed by the dynamics model is missing or null."""


@dataclass(frozen=True)
class Vehicle:
    """Everything the model step, the fit and the export read from vehicle_params."""

    wheelbase_m: float
    steer_min_rad: float
    steer_max_rad: float
    steer_rate_max_rad_per_s: float
    throttle_full_scale_mps: float
    schema_version: str
    sysid_session_id: str
    physical_lock_left_rad: float  # the left stop (largest table angle), for old converted data
    physical_lock_right_rad: float
    body_front_x_m: float  # wheelbase + front overhang
    body_rear_x_m: float  # rear overhang
    body_half_width_m: float
    lidar_x_m: float
    lidar_y_m: float
    lidar_yaw_rad: float

    @classmethod
    def from_binding(cls, vp: Any) -> Vehicle:
        """Build from a generated VehicleParams instance. Raises VehicleParamsError on a null."""

        def need(path: str) -> Any:
            node = vp
            for part in path.split("."):
                node = getattr(node, part, None)
                if node is None:
                    raise VehicleParamsError(f"vehicle_params.{path} is null or missing")
            return node

        table = need("steering.pwm_to_angle_table")
        angles = [float(p.angle_rad) for p in table]
        return cls(
            wheelbase_m=float(need("chassis.wheelbase_m")),
            steer_min_rad=float(need("steering.min_angle_rad")),
            steer_max_rad=float(need("steering.max_angle_rad")),
            steer_rate_max_rad_per_s=float(need("steering.max_rate_rad_per_s")),
            throttle_full_scale_mps=float(need("actuation.throttle_full_scale_mps")),
            schema_version=str(need("meta.schema_version")),
            sysid_session_id=str(need("meta.sysid_session_id")),
            physical_lock_left_rad=max(angles),
            physical_lock_right_rad=min(angles),
            body_front_x_m=float(need("chassis.wheelbase_m"))
            + float(need("chassis.front_overhang_m")),
            body_rear_x_m=float(need("chassis.rear_overhang_m")),
            body_half_width_m=float(need("chassis.width_m")) / 2.0,
            lidar_x_m=float(need("sensors.lidar.mount_x_m")),
            lidar_y_m=float(need("sensors.lidar.mount_y_m")),
            lidar_yaw_rad=float(need("sensors.lidar.mount_yaw_rad")),
        )


def repo_root(start: Path | None = None) -> Path:
    """The checkout root: the nearest parent holding config/vehicle_params.yaml."""
    here = (start or Path(__file__)).resolve()
    for parent in [here, *here.parents]:
        if (parent / PARAMS_RELATIVE).is_file():
            return parent
    raise FileNotFoundError(f"no {PARAMS_RELATIVE} above {here}")


def _load_gen_params(root: Path) -> types.ModuleType:
    path = root / GEN_PARAMS_RELATIVE
    spec = importlib.util.spec_from_file_location("racer_pnp_dynamics._gen_params", path)
    if spec is None or spec.loader is None:  # pragma: no cover - defensive
        raise ImportError(f"could not load {path}")
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module  # dataclasses looks the module up by name
    spec.loader.exec_module(module)
    return module


def load_binding(root: Path | None = None) -> Any:
    """The generated VEHICLE_PARAMS instance, validated against the schema."""
    root = root or repo_root()
    gen = _load_gen_params(root)
    params = gen.load_yaml_file(root / PARAMS_RELATIVE)
    schema = gen.load_schema_file(root / SCHEMA_RELATIVE)
    gen.validate_params(params, schema)
    source = gen.generate_python(params, schema)
    module = types.ModuleType("racer_pnp_dynamics._vehicle_params_generated")
    module.__file__ = "<generated by tools/gen_params.py, not committed>"
    sys.modules[module.__name__] = module
    exec(compile(source, module.__file__, "exec"), module.__dict__)  # noqa: S102
    return module.VEHICLE_PARAMS


def load_vehicle(root: Path | None = None) -> Vehicle:
    return Vehicle.from_binding(load_binding(root))
